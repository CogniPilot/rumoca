"""Write the MJCF variants and a C header of every Modelica parameter the C runner needs."""
import sys, json
import robot
mo, out = sys.argv[1], sys.argv[2]
p = robot.derived(robot.parse_params(mo))
open(f'{out}/twin_hc.xml', 'w').write(robot.mjcf(p, 2.5e-5, 'RK4', native_contact=False))
open(f'{out}/twin_native.xml', 'w').write(robot.mjcf(p, 1e-3, 'implicitfast', native_contact=True))
open(f'{out}/twin_native_act.xml', 'w').write(robot.mjcf(p, 1e-3, 'implicitfast', native_contact=True, actuators=True))
sph = robot.contact_spheres(p)
with open(f'{out}/params.h', 'w') as f:
    f.write('/* generated by gen.py from ' + 'HumanoidPhysical.mo */\n')
    for k in sorted(p):
        f.write(f'#define P_{k} ({p[k]!r})\n')
    f.write(f'#define N_SPH {len(sph)}\n')
    f.write('static const char *SPH_BODY[N_SPH] = {' + ','.join(f'"{b}"' for b, _, _ in sph) + '};\n')
    f.write('static const double SPH_C[N_SPH][3] = {' + ','.join('{%r,%r,%r}' % tuple(map(float, c)) for _, c, _ in sph) + '};\n')
    f.write('static const double SPH_R[N_SPH] = {' + ','.join(repr(float(r)) for _, _, r in sph) + '};\n')
json.dump(p, open(f'{out}/params.json', 'w'), indent=1, sort_keys=True)
print('ok', len(sph), 'spheres')
