fn push_gate_count_row(
    out: &mut String,
    label: &str,
    json: &Value,
    baseline: Option<&Value>,
    count_key: &str,
    denominator_key: Option<&str>,
) {
    let current = json_u64(json, count_key).unwrap_or(0);
    let current_denominator = denominator_key.and_then(|key| json_u64(json, key));
    let Some(baseline) = baseline else {
        out.push_str(&format!(
            "| {label} | {} | n/a | n/a |\n",
            gate_count_cell(current, current_denominator)
        ));
        return;
    };
    let base = json_u64(baseline, count_key).unwrap_or(0);
    let base_denominator = denominator_key.and_then(|key| json_u64(baseline, key));
    out.push_str(&format!(
        "| {label} | {} | {} | {} |\n",
        gate_count_cell(current, current_denominator),
        gate_count_cell(base, base_denominator),
        signed_delta(current, base)
    ));
}

fn gate_count_cell(count: u64, denominator: Option<u64>) -> String {
    denominator.map_or_else(
        || count.to_string(),
        |denominator| format!("{count}/{denominator}"),
    )
}

fn trace_acceptable_gate_row(json: &Value, baseline: Option<&Value>) -> Option<String> {
    let current_trace = json.get("trace_accuracy_stats")?;
    let current =
        json_u64(current_trace, "agreement_high")? + json_u64(current_trace, "agreement_minor")?;
    let current_denominator = json_u64(json, "sim_target_models");
    let Some(baseline) = baseline else {
        return Some(format!(
            "| Trace acceptable floor | {} | n/a | n/a |\n",
            gate_count_cell(current, current_denominator)
        ));
    };
    let base_trace = baseline.get("trace_accuracy_stats")?;
    let base = json_u64(base_trace, "agreement_high")? + json_u64(base_trace, "agreement_minor")?;
    Some(format!(
        "| Trace acceptable floor | {} | {} | {} |\n",
        gate_count_cell(current, current_denominator),
        gate_count_cell(base, json_u64(baseline, "sim_target_models")),
        signed_delta(current, base)
    ))
}

fn trace_no_severe_gate_row(json: &Value, baseline: Option<&Value>) -> Option<String> {
    let current_trace = json.get("trace_accuracy_stats")?;
    let current = trace_no_severe_count(current_trace)?;
    let current_denominator = json_u64(json, "sim_target_models");
    let Some(baseline) = baseline else {
        return Some(format!(
            "| Trace no-severe floor | {} | n/a | n/a |\n",
            gate_count_cell(current, current_denominator)
        ));
    };
    let base = trace_no_severe_count(baseline.get("trace_accuracy_stats")?)?;
    Some(format!(
        "| Trace no-severe floor | {} | {} | {} |\n",
        gate_count_cell(current, current_denominator),
        gate_count_cell(base, json_u64(baseline, "sim_target_models")),
        signed_delta(current, base)
    ))
}

fn trace_no_severe_count(trace: &Value) -> Option<u64> {
    let compared = json_u64(trace, "models_compared")?;
    let severe = json_u64(trace, "models_with_severe_channel")?;
    Some(compared.saturating_sub(severe))
}

fn trace_compared_gate_row(json: &Value, baseline: Option<&Value>) -> Option<String> {
    let current = json_u64(json.get("trace_accuracy_stats")?, "models_compared")?;
    let Some(baseline) = baseline else {
        return Some(format!(
            "| Trace compared floor (drop ≤2) | {current} | n/a | n/a |\n"
        ));
    };
    let base = json_u64(baseline.get("trace_accuracy_stats")?, "models_compared")?;
    Some(format!(
        "| Trace compared floor (drop ≤2) | {current} | {base} | {} |\n",
        signed_delta(current, base)
    ))
}

fn trace_baseline_delta_note(json: &Value, baseline: &Value) -> Option<String> {
    let current = json.get("trace_accuracy_stats")?;
    let base = baseline.get("trace_accuracy_stats")?;
    let current_agree =
        json_u64(current, "agreement_high")? + json_u64(current, "agreement_minor")?;
    let base_agree = json_u64(base, "agreement_high")? + json_u64(base, "agreement_minor")?;
    let current_deviation = json_u64(current, "agreement_deviation")?;
    let base_deviation = json_u64(base, "agreement_deviation")?;
    Some(format!(
        "_Trace agreement vs baseline: high+near Δ{}, deviation Δ{}._\n",
        signed_delta(current_agree, base_agree),
        signed_delta(current_deviation, base_deviation),
    ))
}

fn baseline_identity_note(baseline: &Value) -> String {
    let version = json_u64(baseline, "quality_gate_version")
        .map(|value| value.to_string())
        .unwrap_or_else(|| "unknown".to_string());
    let commit = json_str(baseline, "git_commit")
        .map(short_commit)
        .unwrap_or("unknown");
    let msl = json_str(baseline, "msl_version").unwrap_or("unknown");
    let omc = json_str(baseline, "omc_version").unwrap_or("unknown");
    format!("_Baseline: quality gate v{version}, commit `{commit}`, MSL `{msl}`, OMC `{omc}`._\n")
}

fn short_commit(commit: &str) -> &str {
    commit.get(..7).unwrap_or(commit)
}

fn signed_delta(current: u64, baseline: u64) -> String {
    let delta = current as i128 - baseline as i128;
    if delta > 0 {
        format!("+{delta}")
    } else {
        delta.to_string()
    }
}

fn append_report_section(body: &mut String, title: &str, path: &Path) -> Result<()> {
    if title == "Package Pass Rates" {
        return append_package_pass_rates_section(body, path);
    }

    body.push_str("<details>\n");
    body.push_str(&format!("<summary><strong>{title}</strong></summary>\n\n"));
    if !path.is_file() {
        body.push_str("_Report was not produced in this run._\n\n");
        body.push_str("</details>\n\n");
        return Ok(());
    }
    let text =
        fs::read_to_string(path).with_context(|| format!("failed to read {}", path.display()))?;
    body.push_str(&report_section_text(title, &text));
    body.push_str("\n\n");
    body.push_str("</details>\n\n");
    Ok(())
}

fn append_package_pass_rates_section(body: &mut String, path: &Path) -> Result<()> {
    body.push_str("#### Package Pass Rates\n\n");
    if !path.is_file() {
        body.push_str("_Report was not produced in this run._\n\n");
        return Ok(());
    }
    let text =
        fs::read_to_string(path).with_context(|| format!("failed to read {}", path.display()))?;
    body.push_str(&render_package_pass_rates_section(&text));
    body.push_str("\n\n");
    Ok(())
}

fn report_section_text(title: &str, text: &str) -> String {
    let trimmed = text.trim();
    if title == "Package Pass Rates" {
        strip_time_columns(trimmed)
    } else {
        trimmed.to_string()
    }
}

/// The pass-rate table with its Overall row and column legend shown and the
/// per-package rows folded away.
fn render_package_pass_rates_section(text: &str) -> String {
    let table = strip_time_columns(text.trim());
    let (lines, legend): (Vec<_>, Vec<_>) = table
        .lines()
        .filter(|line| !line.trim().is_empty())
        .partition(|line| line.trim_start().starts_with('|'));
    if lines.len() < 3 {
        return table;
    }

    let header = lines[0];
    let separator = lines[1];
    let (overall_rows, package_rows): (Vec<_>, Vec<_>) = lines[2..]
        .iter()
        .partition(|line| markdown_table_cells(line).first() == Some(&"Overall"));
    if overall_rows.is_empty() {
        return table;
    }

    let mut out = String::new();
    out.push_str(header);
    out.push('\n');
    out.push_str(separator);
    out.push('\n');
    for row in overall_rows {
        out.push_str(row);
        out.push('\n');
    }
    if !legend.is_empty() {
        out.push('\n');
        for line in legend {
            out.push_str(line);
            out.push('\n');
        }
    }
    if !package_rows.is_empty() {
        out.push_str("\n<details>\n");
        out.push_str("<summary><strong>Per-package pass rates</strong></summary>\n\n");
        out.push_str(header);
        out.push('\n');
        out.push_str(separator);
        out.push('\n');
        for row in package_rows {
            out.push_str(row);
            out.push('\n');
        }
        out.push_str("\n</details>");
    }
    out.trim_end().to_string()
}

fn strip_time_columns(text: &str) -> String {
    let mut out = Vec::new();
    let mut time_indices: Option<Vec<usize>> = None;
    // The per-stage `Time` columns are dropped, and their legend line with them.
    let time_legend = legend_prefix("Time");
    for line in text.lines() {
        if line.starts_with(&time_legend) {
            continue;
        }
        if !line.trim_start().starts_with('|') {
            time_indices = None;
            out.push(line.to_string());
            continue;
        }

        let cells = markdown_table_cells(line);
        if time_indices.is_none() {
            let indices = cells
                .iter()
                .enumerate()
                .filter_map(|(index, cell)| (*cell == "Time").then_some(index))
                .collect::<Vec<_>>();
            if !indices.is_empty() {
                time_indices = Some(indices);
            }
        }

        let Some(indices) = time_indices.as_deref() else {
            out.push(line.to_string());
            continue;
        };
        out.push(render_markdown_table_row(&cells, indices));
    }
    out.join("\n")
}

fn markdown_table_cells(line: &str) -> Vec<&str> {
    line.trim()
        .trim_matches('|')
        .split('|')
        .map(str::trim)
        .collect()
}

fn render_markdown_table_row(cells: &[&str], remove_indices: &[usize]) -> String {
    let kept = cells
        .iter()
        .enumerate()
        .filter_map(|(index, cell)| (!remove_indices.contains(&index)).then_some(*cell))
        .collect::<Vec<_>>();
    format!("| {} |", kept.join(" | "))
}

fn append_optional_link_note(body: &mut String, results_dir: &Path) {
    let compatibility = results_dir.join("msl_compatibility_report.md");
    let modelica_test = results_dir.join("modelica_test_catalog.md");
    if !compatibility.is_file() && !modelica_test.is_file() {
        return;
    }

    body.push_str("#### Additional Artifacts\n\n");
    if compatibility.is_file() {
        body.push_str("- `msl_compatibility_report.md`\n");
    }
    if modelica_test.is_file() {
        body.push_str("- `modelica_test_catalog.md`\n");
    }
    body.push('\n');
}

fn json_str<'a>(json: &'a Value, key: &str) -> Option<&'a str> {
    json.get(key).and_then(Value::as_str)
}

fn json_u64(json: &Value, key: &str) -> Option<u64> {
    json.get(key).and_then(Value::as_u64)
}

fn json_f64(json: &Value, key: &str) -> Option<f64> {
    json.get(key).and_then(Value::as_f64)
}

fn positive_json_f64(json: &Value, key: &str) -> Option<f64> {
    let value = json_f64(json, key)?;
    (value.is_finite() && value > 0.0).then_some(value)
}

fn nonnegative_json_f64(json: &Value, key: &str) -> Option<f64> {
    let value = json_f64(json, key)?;
    (value.is_finite() && value >= 0.0).then_some(value)
}

