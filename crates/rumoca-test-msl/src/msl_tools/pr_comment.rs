const DEFAULT_RESULTS_DIR: &str = "target/msl/results";
const DEFAULT_OUTPUT_FILE: &str = "msl_pr_comment.md";
const DEFAULT_BASELINE_FILE: &str =
    "crates/rumoca-test-msl/tests/msl_tests/msl_quality_baseline.json";
const COMMENT_MARKER: &str = "<!-- rumoca-msl-quality-summary -->";

#[derive(Debug, clap::Args, Clone)]
pub struct Args {
    /// MSL results directory containing markdown report artifacts
    #[arg(long, default_value = DEFAULT_RESULTS_DIR)]
    pub results_dir: PathBuf,
    /// Markdown file to write for CI PR publication
    #[arg(long)]
    pub out: Option<PathBuf>,
    /// Quality baseline used to render summary deltas
    #[arg(long, default_value = DEFAULT_BASELINE_FILE)]
    pub baseline: PathBuf,
}

pub fn run(args: Args) -> Result<()> {
    let out = args
        .out
        .clone()
        .unwrap_or_else(|| args.results_dir.join(DEFAULT_OUTPUT_FILE));
    if let Some(parent) = out.parent() {
        fs::create_dir_all(parent)
            .with_context(|| format!("failed to create {}", parent.display()))?;
    }
    let body = render_pr_comment(&args.results_dir, Some(&args.baseline))?;
    fs::write(&out, body).with_context(|| format!("failed to write {}", out.display()))?;
    println!("MSL PR comment summary written to {}", out.display());
    Ok(())
}

fn render_pr_comment(results_dir: &Path, baseline_path: Option<&Path>) -> Result<String> {
    let mut body = String::new();
    body.push_str(COMMENT_MARKER);
    body.push_str("\n### MSL Quality Gate Summary\n\n");
    body.push_str("_Generated by `cargo xtask repo msl pr-comment` from CI result artifacts._\n\n");

    if let Some(summary) = render_quality_snapshot_summary(results_dir, baseline_path)? {
        body.push_str(&summary);
        body.push('\n');
    }

    body.push_str("#### Simulation Soundness Roster\n\n");
    let baseline = load_quality_baseline(baseline_path)?;
    body.push_str(&render_soundness_section(results_dir, baseline.as_ref())?);
    body.push('\n');

    append_report_section(
        &mut body,
        "Package Pass Rates",
        &results_dir.join("msl_package_pass_rates.md"),
    )?;
    append_report_section(
        &mut body,
        "MLS Contract Coverage",
        &results_dir.join("mls_contract_coverage.md"),
    )?;
    append_report_section(
        &mut body,
        "Trace Accuracy vs OMC",
        &results_dir.join("msl_package_trace_accuracy.md"),
    )?;
    body.push_str("#### Speed vs OMC\n\n");
    body.push_str(&render_speed_section(results_dir)?);
    body.push_str("\n\n");
    append_optional_link_note(&mut body, results_dir);

    Ok(body)
}

fn render_quality_snapshot_summary(
    results_dir: &Path,
    baseline_path: Option<&Path>,
) -> Result<Option<String>> {
    let quality_path = results_dir.join("msl_quality_current.json");
    if !quality_path.is_file() {
        return Ok(None);
    }
    let text = fs::read_to_string(&quality_path)
        .with_context(|| format!("failed to read {}", quality_path.display()))?;
    let json: Value = serde_json::from_str(&text)
        .with_context(|| format!("failed to parse {}", quality_path.display()))?;
    let baseline = load_quality_baseline(baseline_path)?;

    let run_scope = json_str(&json, "run_scope").unwrap_or("unknown");
    let msl_version = json_str(&json, "msl_version").unwrap_or("unknown");
    let omc_version = json_str(&json, "omc_version").unwrap_or("unknown");
    let compile = quality_metric_cell(
        &json,
        baseline.as_ref(),
        "compiled_models",
        "simulatable_attempted",
    );
    let balance = quality_metric_cell(
        &json,
        baseline.as_ref(),
        "balanced_models",
        "balance_denominator",
    );
    let initial_balance = quality_metric_cell(
        &json,
        baseline.as_ref(),
        "initial_balanced_models",
        "balance_denominator",
    );
    let simulation = quality_metric_cell(&json, baseline.as_ref(), "sim_ok", "sim_target_models");
    let mut delta_note = String::new();
    if let Some(baseline) = baseline.as_ref() {
        delta_note.push_str(
            "\n_Deltas compare numerator/denominator against the resolved MSL quality baseline._\n",
        );
        delta_note.push_str(&baseline_identity_note(baseline));
        if let Some(trace_note) = trace_baseline_delta_note(&json, baseline) {
            delta_note.push_str(&trace_note);
        }
    }

    let outcomes = render_outcomes_section(results_dir, &json)?;
    let ci_gate_metrics = render_ci_gate_metrics_table(&json, baseline.as_ref());

    Ok(Some(format!(
        "| Scope | MSL | OMC | Compile | Balance | Initial Balance | Simulated |\n\
         |---|---|---|---:|---:|---:|---:|\n\
         | `{run_scope}` | `{msl_version}` | `{omc_version}` | {compile} | {balance} | {initial_balance} | {simulation} |\n\
         {delta_note}\n\
         {outcomes}\n\
         {ci_gate_metrics}"
    )))
}

fn load_quality_baseline(path: Option<&Path>) -> Result<Option<Value>> {
    let Some(path) = path else {
        return Ok(None);
    };
    if !path.is_file() {
        return Ok(None);
    }
    let text =
        fs::read_to_string(path).with_context(|| format!("failed to read {}", path.display()))?;
    serde_json::from_str(&text)
        .map(Some)
        .with_context(|| format!("failed to parse {}", path.display()))
}

fn quality_metric_cell(
    json: &Value,
    baseline: Option<&Value>,
    num_key: &str,
    den_key: &str,
) -> String {
    let numerator = json_u64(json, num_key).unwrap_or(0);
    let denominator = json_u64(json, den_key).unwrap_or(0);
    let Some(baseline) = baseline else {
        return format!("{numerator}/{denominator}");
    };
    let base_numerator = json_u64(baseline, num_key).unwrap_or(0);
    let base_denominator = json_u64(baseline, den_key).unwrap_or(0);
    format!(
        "{numerator}/{denominator} (Δ{}/{})",
        signed_delta(numerator, base_numerator),
        signed_delta(denominator, base_denominator)
    )
}

fn render_ci_gate_metrics_table(json: &Value, baseline: Option<&Value>) -> String {
    let mut out = String::from(
        "#### CI Gate Snapshot\n\n\
         _These are the baseline-relative MSL stats checked by CI; IC progress is contextual unless simulation successes regress, and speed metrics are informational only._\n\n\
         | Gate area | Current (Δ vs baseline) |\n\
         |---|---:|\n",
    );
    out.push_str(&compact_structural_gate_row(json, baseline));
    out.push_str(&compact_balance_gate_row(json, baseline));
    out.push_str(&compact_runtime_gate_row(json, baseline));
    if let Some(row) = compact_trace_gate_row(json, baseline) {
        out.push_str(&row);
    }
    out.push_str("\n<details>\n<summary><strong>CI gate details</strong></summary>\n\n");
    out.push_str(&render_ci_gate_detail_table(json, baseline));
    out.push_str("\n</details>\n");
    out
}

fn compact_structural_gate_row(json: &Value, baseline: Option<&Value>) -> String {
    let keys = [
        ("parse", "parse_models"),
        ("flat", "flatten_models"),
        ("DAE", "compiled_models"),
        ("solve", "solve_models"),
    ];
    compact_gate_row("Structural floors", json, baseline, &keys, None)
}

fn compact_balance_gate_row(json: &Value, baseline: Option<&Value>) -> String {
    let keys = [
        ("balance", "balanced_models"),
        ("init", "initial_balanced_models"),
    ];
    compact_gate_row(
        "Balance floors",
        json,
        baseline,
        &keys,
        Some("balance_denominator"),
    )
}

fn compact_runtime_gate_row(json: &Value, baseline: Option<&Value>) -> String {
    let keys = [("IC progress", "ic_ok"), ("sim", "sim_ok")];
    compact_gate_row(
        "Runtime gate",
        json,
        baseline,
        &keys,
        Some("sim_target_models"),
    )
}

fn compact_gate_row(
    label: &str,
    json: &Value,
    baseline: Option<&Value>,
    keys: &[(&str, &str)],
    denominator_key: Option<&str>,
) -> String {
    let current = compact_gate_values(json, keys, denominator_key);
    let Some(baseline) = baseline else {
        return format!("| {label} | {current} |\n");
    };
    let values = keys
        .iter()
        .map(|(name, key)| {
            let current = json_u64(json, key).unwrap_or(0);
            let base = json_u64(baseline, key).unwrap_or(0);
            let denominator = denominator_key.and_then(|key| json_u64(json, key));
            format!(
                "{name} {} ({})",
                gate_count_cell(current, denominator),
                signed_delta(current, base)
            )
        })
        .collect::<Vec<_>>()
        .join(", ");
    format!("| {label} | {values} |\n")
}

fn compact_gate_values(
    json: &Value,
    keys: &[(&str, &str)],
    denominator_key: Option<&str>,
) -> String {
    let denominator = denominator_key.and_then(|key| json_u64(json, key));
    keys.iter()
        .map(|(name, key)| {
            let count = json_u64(json, key).unwrap_or(0);
            format!("{name} {}", gate_count_cell(count, denominator))
        })
        .collect::<Vec<_>>()
        .join(", ")
}

fn compact_trace_gate_row(json: &Value, baseline: Option<&Value>) -> Option<String> {
    let current_trace = json.get("trace_accuracy_stats")?;
    let current_acceptable =
        json_u64(current_trace, "agreement_high")? + json_u64(current_trace, "agreement_minor")?;
    let current_no_severe = trace_no_severe_count(current_trace)?;
    let current_compared = json_u64(current_trace, "models_compared")?;
    let current_target = json_u64(json, "sim_target_models");
    let current = format!(
        "acceptable {}, no-severe {}, compared {}",
        gate_count_cell(current_acceptable, current_target),
        gate_count_cell(current_no_severe, current_target),
        current_compared,
    );
    let Some(baseline) = baseline else {
        return Some(format!("| Trace floors | {current} |\n"));
    };
    let base_trace = baseline.get("trace_accuracy_stats")?;
    let base_acceptable =
        json_u64(base_trace, "agreement_high")? + json_u64(base_trace, "agreement_minor")?;
    let base_no_severe = trace_no_severe_count(base_trace)?;
    let base_compared = json_u64(base_trace, "models_compared")?;
    let values = format!(
        "acceptable {} ({}), no-severe {} ({}), compared {} ({})",
        gate_count_cell(current_acceptable, current_target),
        signed_delta(current_acceptable, base_acceptable),
        gate_count_cell(current_no_severe, current_target),
        signed_delta(current_no_severe, base_no_severe),
        current_compared,
        signed_delta(current_compared, base_compared),
    );
    Some(format!("| Trace floors | {values} |\n"))
}

